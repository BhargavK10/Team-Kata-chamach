-- 1. Create table to store historical risk score snapshots
CREATE TABLE IF NOT EXISTS public.company_risk_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name TEXT NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    overall_risk_score INT NOT NULL CHECK (overall_risk_score >= 0 AND overall_risk_score <= 100),
    risk_level TEXT NOT NULL,
    escalated_threats_count INT DEFAULT 0,
    noise_items_count INT DEFAULT 0,
    score_rationale TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Create index for fast time-series queries by company
CREATE INDEX IF NOT EXISTS idx_company_risk_history_company 
ON public.company_risk_history (company_name, timestamp DESC);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.company_risk_history ENABLE ROW LEVEL SECURITY;

-- 4. Allow public / anonymous reads and inserts via publishable key
CREATE POLICY "Allow public read access" 
ON public.company_risk_history 
FOR SELECT 
TO anon, authenticated 
USING (true);

CREATE POLICY "Allow public insert access" 
ON public.company_risk_history 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

